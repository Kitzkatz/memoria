"""
Interactive plugin generator for Memoria.

Generates a local Memoria plugin module and optional supporting files.
The generated plugin is compatible with the existing MemoriaPluginManager
local-plugin discovery mechanism.
"""

from __future__ import annotations

import re
from pathlib import Path


